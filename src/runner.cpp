/// The vertices of a triangle of the runner, in the winding of the mesh it came from
using RunnerFace = std::array<std::uint16_t, 3>;

/// A triangle whose winding says which way it faces, for a mesh that is not convex. The builder points a normal away
/// from the centre, so the centre goes just behind the face, along the normal the winding gives.
void WoundTri(ModelBuilder& b, const RunnerFace& face, Rgb colour) {
  const Vec3 p0 = b.Position(face[0]);
  const Vec3 p1 = b.Position(face[1]);
  const Vec3 p2 = b.Position(face[2]);
  const Vec3 u{p1.x - p0.x, p1.y - p0.y, p1.z - p0.z};
  const Vec3 v{p2.x - p0.x, p2.y - p0.y, p2.z - p0.z};
  const Vec3 n{u.y * v.z - u.z * v.y, u.z * v.x - u.x * v.z, u.x * v.y - u.y * v.x};
  const float length = std::sqrt(n.x * n.x + n.y * n.y + n.z * n.z);
  if (length < 1e-9f) {
    return;  // no area, so nothing to see
  }
  b.Centre((p0.x + p1.x + p2.x) / 3.0f - n.x / length, (p0.y + p1.y + p2.y) / 3.0f - n.y / length,
           (p0.z + p1.z + p2.z) / 3.0f - n.z / length);
  b.Tri(face[0], face[1], face[2], colour, false, 0);  // no edges: a runner is solid, not a wireframe
}

